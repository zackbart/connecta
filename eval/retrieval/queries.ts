import type { Deployment } from "./catalogs.js";

export type QueryType = "intent" | "precise" | "write" | "hatch" | "vague" | "multi";

export interface RetrievalQuery {
  deployment: Deployment;
  type: QueryType;
  query: string;
  answers: readonly string[];
  uncertain?: true;
}

type Row = readonly [type: QueryType, query: string, answers: readonly string[], uncertain?: 1];

const rows = (deployment: Deployment, list: readonly Row[]): RetrievalQuery[] =>
  list.map(([type, query, answers, uncertain]) => ({
    deployment,
    type,
    query,
    answers,
    ...(uncertain ? { uncertain: true as const } : {}),
  }));

