import { readFile, writeFile } from "node:fs/promises";
import { basename, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = resolve(root, "src/operator-ui/generated.ts");
const checkOnly = process.argv.includes("--check");

const result = await build({
  absWorkingDir: root,
  bundle: true,
  charset: "utf8",
  entryNames: "[name]",
  entryPoints: {
    script: "src/operator-ui/browser.ts",
    styles: "src/operator-ui/browser.css",
  },
  format: "iife",
  legalComments: "none",
  logLevel: "silent",
  minify: false,
  outdir: "operator-ui-build",
  platform: "browser",
  target: "es2022",
  treeShaking: true,
  write: false,
});

const output = new Map(
  result.outputFiles.map((file) => [
    basename(file.path),
    file.text,
  ]),
);
const script = output.get("script.js");
const styles = output.get("styles.css");
if (script === undefined || styles === undefined) {
  throw new Error("Operator UI build did not produce script.js and styles.css");
}
if (/<\/script/i.test(script)) {
  throw new Error("Operator UI bundle contains a closing script tag");
}
if (/<\/style/i.test(styles)) {
  throw new Error("Operator UI stylesheet contains a closing style tag");
}

const generated = `// Generated by scripts/build-operator-ui.mjs. Do not edit.
// Source: src/operator-ui/browser.ts and src/operator-ui/browser.css.
export const OPERATOR_UI_CSS = ${JSON.stringify(styles)};
export const OPERATOR_UI_SCRIPT = ${JSON.stringify(script)};
`;

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(generatedPath, "utf8");
  } catch {
    // The mismatch below reports the one actionable command.
  }
  if (current !== generated) {
    console.error(
      `${relative(root, generatedPath)} is stale; run npm run build:operator-ui`,
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(generatedPath, generated);
}
