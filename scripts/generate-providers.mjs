// Folder discovery derives every provider list, and decision 0011's
// generated artifacts: `skill.generated.ts` (the guide and its Conventions)
// and `drift.json`'s `generated` block. Every provider must meet D and G;
// violations are refused before writing any output.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { readFile, realpath, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import { generatedBlock, serializeDrift } from "./drift-record.mjs";
import { DRIFT_VERSION } from "./drift-validate.mjs";
import { checkOpenApiOutputs } from "./generate-openapi.mjs";
import { parseGuide, renderConventions } from "./provider-guide.mjs";
import { discoverProviders, EVAL_FILES, repositoryRoot } from "./providers.mjs";

const generated = "// Generated by scripts/generate-providers.mjs; do not edit.\n";
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
/** The rule checks of decision 0011, shared with the provider-standard suite. */
const STANDARD_RULES = fileURLToPath(new URL("../test/provider-standard.ts", import.meta.url));

function fail(name, message) {
  throw new Error(`providers/${name}: ${message}`);
}

function replaceEntries(entries, providers, makeEntry) {
  const output = {};
  let inserted = false;
  for (const [key, value] of Object.entries(entries)) {
    if (key.startsWith("./providers/")) {
      if (!inserted) {
        for (const provider of providers) output[`./providers/${provider.name}`] = makeEntry(provider);
        inserted = true;
      }
    } else output[key] = value;
  }
  if (!inserted) for (const provider of providers) output[`./providers/${provider.name}`] = makeEntry(provider);
  return output;
}

function knipEntries(source, providers) {
  const entries = /("entry"\s*:\s*\[)([\s\S]*?)(\n\s*\])/.exec(source);
  if (!entries) throw new Error("knip.jsonc requires an entry array");
  // Own public provider entries, including retired flat entries. Explicit
  // fixture entrypoints belong to their dynamic consumers and stay intact.
  const membership = /^\s*"src\/providers\/(?:[^/"\n]+\.ts|[^"\n]+\/index\.ts)"\s*,?[^\n]*\n/gm;
  const matches = [...entries[2].matchAll(membership)];
  const position = matches[0]?.index ?? entries[2].length;
  const before = entries[2].slice(0, position);
  const after = entries[2].slice(position).replace(membership, "");
  const indent = /\n([ \t]*)\]/.exec(entries[3])?.[1] ?? "  ";
  const additions = providers.map(({ name }) => `${indent}  "src/providers/${name}/index.ts",\n`).join("");
  return source.replace(
    entries[0],
    entries[1] + before + (before.endsWith("\n") ? "" : "\n") + additions + after + entries[3],
  );
}

function readmeList(source, providers) {
  const names = providers
    .map(({ definition }) => definition.readme ?? definition.title)
    .sort((a, b) => a.localeCompare(b, "en"));
  const list = names.length <= 1 ? names.join("") : `${names.slice(0, -1).join(", ")}, and ${names.at(-1)}`;
  const start = "<!-- providers:start -->";
  const end = "<!-- providers:end -->";
  if (source.includes(start) || source.includes(end)) {
    if (
      source.split(start).length !== 2 ||
      source.split(end).length !== 2 ||
      source.indexOf(end) < source.indexOf(start)
    ) {
      throw new Error("README provider list requires one ordered pair of providers:start/end markers");
    }
    return source.slice(0, source.indexOf(start) + start.length) + list + source.slice(source.indexOf(end));
  }
  const existing = /(\*\*Use maintained connections\*\* for )([\s\S]*?)(: known endpoints)/.exec(source);
  if (!existing) throw new Error("README.md is missing the bounded maintained connections list");
  return source.replace(existing[0], `${existing[1]}${start}${list}${end}${existing[3]}`);
}

/**
 * A provider without a `## <display>` setup section gets a mechanical skeleton
 * at the end of documentation/providers.md: the heading and its construction
 * import. The marker keeps the standard suite failing (G7) until the setup is
 * written and the marker removed.
 */
function setupSkeleton(source, { name, factoryName, definition }, marker) {
  const display = definition.readme ?? definition.title;
  if (source.split(/\r?\n/).includes(`## ${display}`)) return source;
  return [
    source.trimEnd(),
    "",
    `## ${display}`,
    "",
    `${marker(name)} Replace this line with the construction example's purpose and options, the credential, vendor prerequisites and limits.`,
    "",
    "```ts",
    `import { ${factoryName} } from "@zackbart/connecta/providers/${name}";`,
    "```",
    "",
  ].join("\n");
}

/** The installed inventory uses the same offline catalogs as generated conventions. */
async function providerInventory(source, providers) {
  const start = "<!-- provider-inventory:start -->";
  const end = "<!-- provider-inventory:end -->";
  const entries = [];
  for (const provider of providers) {
    const { name, definition, tools, conventionToolBlocks = {}, driftData } = provider;
    const display = definition.readme ?? definition.title;
    const setup = display
      .toLowerCase()
      .replace(/[^\p{L}\p{N}_ -]/gu, "")
      .replace(/ /g, "-");
    const evidence = `https://github.com/zackbart/connecta/tree/main/src/providers/${name}`;
    const readPin = async (file) => JSON.parse(await readFile(join(provider.directory, "evidence", file), "utf8"));
    let pin;
    try {
      pin = await readPin("openapi.json");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    const checks = driftData.checks ?? [];
    const specifications = checks.flatMap((check) => (check.specification ? [check.specification] : []));
    const link = (label, record) => `[${label}](${record.documentation ?? record.latest ?? record.url})`;
    let provenance;
    if (pin?.documents) {
      const documents = await Promise.all(pin.documents.map(({ pin: file }) => readPin(file)));
      provenance = `Composed upstream OpenAPI contracts: ${documents.map((record, i) => link(pin.documents[i].prefix, record)).join(", ")}.`;
    } else if (pin) {
      const conversion = specifications.some(({ url }) => url && !url.startsWith("https://"));
      const kind = pin.discovery
        ? "Google Discovery conversion"
        : conversion
          ? "Reviewed HTML/documentation conversion"
          : "Upstream OpenAPI";
      provenance = `${link(kind, pin)}.`;
    } else {
      const checks = specifications.map((record) => link("upstream endpoint checks", record)).join(", ");
      provenance = `Hand-authored endpoint contracts${checks ? `; ${checks}` : ""}. No vendored OpenAPI document.`;
    }
    for (const specification of specifications) {
      if (!specification.pin || specification.pin === pin?.discovery?.pin) continue;
      provenance += ` ${link("Supplemental reviewed contract", await readPin(specification.pin))}.`;
    }
    const groups = new Map();
    for (const tool of tools) {
      const api = tool.name.startsWith(`${definition.kit?.hatch?.name}_api_`);
      const read = tool.annotations?.readOnlyHint === true && tool.annotations?.destructiveHint !== true;
      const group = `${api ? "API" : "Named"} ${read ? "reads" : "writes"}`;
      const conditional = conventionToolBlocks[tool.name];
      const label = `\`${tool.name}\`${conditional ? ` (${conditional} enabled)` : ""}`;
      groups.set(group, [...(groups.get(group) ?? []), label]);
    }
    entries.push(
      [
        "<details>",
        `<summary>${display} (${tools.length} tools)</summary>`,
        "",
        `[Setup](#${setup}). **API source:** ${provenance}`,
        "",
        ...["Named reads", "Named writes", "API reads", "API writes"].map(
          (group) => `- **${group}:** ${groups.get(group)?.sort().join(", ") ?? "None"}.`,
        ),
        "",
        `**Contributor evidence (optional):** [contracts, adapters and review](${evidence}).`,
        "",
        "</details>",
      ].join("\n"),
    );
  }
  const block = `${start}\n\n${entries.join("\n\n")}\n\n${end}`;
  // Fixture roots and older pages may predate the bounded inventory.
  if (!source.includes(start) && !source.includes(end)) return `${source.trimEnd()}\n\n${block}\n`;
  if (
    source.split(start).length !== 2 ||
    source.split(end).length !== 2 ||
    source.indexOf(end) < source.indexOf(start)
  ) {
    throw new Error("Provider inventory requires one ordered pair of provider-inventory:start/end markers");
  }
  return source.slice(0, source.indexOf(start)) + block + source.slice(source.indexOf(end) + end.length);
}

/** Import a TypeScript module's exports by bundling it; the generator runs under plain Node too. */
async function importBundle(options) {
  const result = await build({
    bundle: true,
    write: false,
    platform: "node",
    format: "esm",
    packages: "external",
    logLevel: "silent",
    ...options,
  });
  return import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`);
}

function walk(directory, prefix = "") {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(directory, entry.name), `${prefix}${entry.name}/`) : [`${prefix}${entry.name}`],
  );
}

// Bundling is a loader here, not a production build. Virtual skill modules
// allow --check to import current definitions even when generated files are
// missing or stale, without a write or a stale-module import deadlock.
async function loadDefinition(provider, skills) {
  const exports = await importBundle({
    stdin: {
      contents: `export * from ${JSON.stringify(provider.index)}; export * from ${JSON.stringify(provider.fixtures)};`,
      resolveDir: provider.directory,
      loader: "ts",
    },
    plugins: [
      {
        name: "current-provider-skills",
        setup(buildContext) {
          buildContext.onResolve({ filter: /skill\.generated\.(?:js|ts)$/ }, (args) => ({
            path: join(args.resolveDir, "skill.generated.ts"),
            namespace: "skill",
          }));
          buildContext.onLoad({ filter: /.*/, namespace: "skill" }, ({ path }) => {
            if (!skills.has(path)) throw new Error(`Unknown generated skill ${path}`);
            return { contents: skills.get(path), loader: "ts" };
          });
          buildContext.onResolve({ filter: /^[^./]/ }, (args) => {
            if (args.path.startsWith("node:")) return { path: args.path, external: true };
            return { path: import.meta.resolve(args.path), external: true };
          });
        },
      },
    ],
  });
  const factories = Object.entries(exports).filter(
    ([, value]) => typeof value === "function" && value.definition !== undefined,
  );
  if (factories.length !== 1) fail(provider.name, "index.ts must export exactly one factory with .definition");
  const [factoryName, { definition }] = factories[0];
  provider.factoryName = factoryName;
  if (
    definition.name !== provider.name ||
    typeof definition.title !== "string" ||
    !definition.title.trim() ||
    definition.kind !== "api"
  )
    fail(provider.name, "invalid factory definition");
  // Provider entries are reported against a baseline, never capped: see the
  // policy note in scripts/bundle-budget.json.
  const { baselineGzip, note, ...rest } = definition.bundle ?? {};
  if (
    !Number.isSafeInteger(baselineGzip) ||
    baselineGzip < 0 ||
    Object.keys(rest).length > 0 ||
    (note !== undefined && typeof note !== "string")
  )
    fail(provider.name, "definition requires valid bundle baselineGzip and optional note, and no cap");
  if (
    definition.readme !== undefined &&
    (typeof definition.readme !== "string" || !definition.readme.trim() || /[\r\n]/.test(definition.readme))
  ) {
    fail(provider.name, "definition.readme must be a non-empty single-line display name");
  }
  if (typeof exports.createAuthored !== "function")
    fail(provider.name, "fixtures.ts must export createAuthored() with nonempty staticTools for generated conventions");
  const tools = exports.createAuthored()?.staticTools;
  if (!Array.isArray(tools) || !tools.length)
    fail(provider.name, "createAuthored().staticTools must be a nonempty offline tool catalog");
  provider.tools = tools;
  provider.conventionToolBlocks = exports.conventionToolBlocks;
  return definition;
}

async function smokeFixtures(root, providers) {
  const imports = providers
    .map(({ fixtures }, index) => `import { fixture as fixture${index} } from ${JSON.stringify(fixtures)};`)
    .join("\n");
  const providerIndices = new Map(providers.map(({ index, name }) => [index, name]));
  const result = await build({
    stdin: {
      contents: `${imports}\nexport const fixtures = [${providers.map((_, index) => `fixture${index}`).join(", ")}];\n`,
      resolveDir: root,
      sourcefile: "provider-smoke.ts",
      loader: "ts",
    },
    absWorkingDir: root,
    bundle: true,
    write: false,
    platform: "node",
    format: "esm",
    packages: "external",
    logLevel: "silent",
    plugins: [
      {
        name: "installed-providers",
        setup(buildContext) {
          buildContext.onResolve({ filter: /^\./ }, (args) => {
            const path = resolve(args.resolveDir, args.path.replace(/\.js$/, ".ts"));
            const name = providerIndices.get(path);
            return name ? { path: `@zackbart/connecta/providers/${name}`, external: true } : undefined;
          });
        },
      },
    ],
  });
  return generated + result.outputFiles[0].text;
}

/**
 * The shared eval registrations for provider-local eval wiring
 * (eval/support/provider-eval.ts): one module per role, so the Node-free
 * deploy registry never imports a Node-only fake or task.
 */
async function evalRegistrations(root, providers) {
  const evals = providers.filter((provider) => provider.eval);
  for (const provider of evals) {
    for (const [file, name] of Object.entries(EVAL_FILES)) {
      const source = await readFile(join(provider.directory, "eval", file), "utf8");
      if (!new RegExp(`^export const ${name}\\b`, "m").test(source))
        fail(provider.name, `eval/${file} must export const ${name}`);
    }
  }
  const from = (directory, path) => {
    const specifier = relative(join(root, "eval", directory), path)
      .replaceAll("\\", "/")
      .replace(/\.ts$/, ".js");
    return JSON.stringify(specifier);
  };
  const imports = (directory, role, alias) =>
    evals
      .map(
        ({ eval: files }, index) =>
          `import { ${EVAL_FILES[`${role}.ts`]} as ${alias}${index} } from ${from(directory, files[role])};\n`,
      )
      .join("");
  const entries = (alias, render = (index) => `${alias}${index}`) =>
    evals.map(({ name }, index) => `  ${JSON.stringify(name)}: ${render(index)},\n`).join("");
  return new Map([
    [
      join(root, "eval", "fakes", "providers.generated.ts"),
      generated +
        imports("fakes", "fake", "fake") +
        `\n/** Provider-local fakes (src/providers/<name>/eval/fake.ts), by provider name. */\nexport const PROVIDER_FAKES = {\n${entries("fake")}};\n`,
    ],
    [
      join(root, "eval", "deploy", "providers.generated.ts"),
      generated +
        'import type { ProviderDeploy } from "../support/provider-eval.js";\n' +
        imports("deploy", "deploy", "deploy") +
        `\n/** Provider-local connectors (src/providers/<name>/eval/deploy.ts), by provider name. Node-free. */\nexport const PROVIDER_DEPLOYS: Readonly<Record<string, ProviderDeploy>> = {\n${entries("deploy")}};\n`,
    ],
    [
      join(root, "eval", "tasks", "providers.generated.ts"),
      generated +
        'import type { ProviderTasks } from "../support/provider-eval.js";\n' +
        imports("tasks", "tasks", "tasks") +
        "\n/** Provider-local tasks (src/providers/<name>/eval/tasks.ts) and any dedicated smoke Worker, in folder order. */\n" +
        "export const PROVIDER_EVALS: readonly { name: string; worker?: string; tasks: ProviderTasks }[] = [\n" +
        evals
          .map(
            ({ name, eval: files }, index) =>
              `  { name: ${JSON.stringify(name)}, ${files.worker ? `worker: ${JSON.stringify(relative(root, files.worker).replaceAll("\\", "/"))}, ` : ""}tasks: tasks${index} },\n`,
          )
          .join("") +
        "];\n",
    ],
  ]);
}

const skillModule = (skill) => `${generated}export const skill = ${JSON.stringify(skill, null, 2)} as const;\n`;

export async function generateProviders({ root = repositoryRoot, check = false } = {}) {
  root = await realpath(resolve(root));
  const providers = await discoverProviders(root);
  const outputs = new Map();
  const skills = new Map();
  // Finish every skill before any provider definition is imported. A
  // standard guide's Conventions need its definition, so its heading stands
  // in until the definitions load.
  for (const provider of providers) {
    const source = await readFile(provider.skill, "utf8");
    provider.guide = parseGuide(source, provider.name);
    provider.skillData = {
      content: [provider.guide.body, "## Conventions"].filter(Boolean).join("\n\n"),
      instructionsHeading: provider.guide.instructionsHeading,
    };
    const path = join(provider.directory, "skill.generated.ts");
    skills.set(path, skillModule(provider.skillData));
    outputs.set(path, skills.get(path));
  }
  const violations = [];
  const today = new Date().toISOString().slice(0, 10);
  let documentation = await readFile(join(root, "documentation", "providers.md"), "utf8").catch((error) => {
    if (error.code === "ENOENT") return "";
    throw error;
  });
  const rules = await importBundle({ entryPoints: [STANDARD_RULES] });
  for (const provider of providers) {
    const definition = (provider.definition = await loadDefinition(provider, skills));
    if (JSON.stringify(definition.skill) !== JSON.stringify(provider.skillData))
      fail(provider.name, "definition.skill must read the generated SKILL.md module");
    let drift;
    try {
      drift = JSON.parse(await readFile(provider.drift, "utf8"));
    } catch {
      fail(provider.name, "drift.json must contain valid JSON");
    }
    provider.driftData = drift;
    const keys = definition.blocks?.keys ?? [];
    for (const key of provider.guide.keys) {
      if (!keys.includes(key)) fail(provider.name, `G2: SKILL.md uses the when-block ${key}, which blocks.keys omits`);
    }
    const conventions = renderConventions({
      name: provider.name,
      kind: definition.kind,
      kit: definition.kit,
      tools: provider.tools,
      keys,
      toolBlocks: provider.conventionToolBlocks,
    });
    const skill = {
      content: [provider.guide.body, conventions].filter(Boolean).join("\n\n"),
      instructionsHeading: provider.guide.instructionsHeading,
    };
    outputs.set(join(provider.directory, "skill.generated.ts"), skillModule(skill));
    // drift.json version 2: tools write the lists and digests (D2).
    let driftText;
    if (drift?.version === DRIFT_VERSION) {
      const block = await generatedBlock({
        directory: provider.directory,
        kind: definition.kind,
        kit: definition.kit,
      });
      driftText = serializeDrift({ ...drift, generated: block });
      outputs.set(provider.drift, driftText);
    }
    // Every provider must meet the drift and guide rules (D, G).
    // D includes what providers:check cannot read (drift-validate.mjs); a new
    // endpoint row may await the contract `providers:check --record` writes.
    const files = walk(provider.directory).sort();
    const facts = {
      name: provider.name,
      kind: definition.kind,
      display: definition.readme ?? definition.title,
      files,
      read: (path) =>
        path === "drift.json" && driftText !== undefined
          ? driftText
          : files.includes(path)
            ? readFileSync(join(provider.directory, path), "utf8")
            : undefined,
      blockKeys: keys,
    };
    if (documentation) documentation = setupSkeleton(documentation, provider, rules.setupSkeleton);
    const found = [
      ...rules.driftViolations(facts, today, { recording: true }),
      ...rules.guideViolations(facts, documentation, { skeleton: true }),
    ];
    violations.push(...found.map((finding) => `providers/${provider.name}: ${finding}`));
  }
  if (violations.length) {
    throw new Error(`Provider standard violations (decision 0011); nothing was written:\n${violations.join("\n")}`);
  }
  const manifestPath = join(root, "package.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  manifest.exports = replaceEntries(manifest.exports, providers, ({ name }) => ({
    types: `./dist/providers/${name}/index.d.ts`,
    import: `./dist/providers/${name}/index.js`,
  }));
  outputs.set(manifestPath, json(manifest));
  const knipPath = join(root, "knip.jsonc");
  outputs.set(knipPath, knipEntries(await readFile(knipPath, "utf8"), providers));
  const budgetPath = join(root, "scripts", "bundle-budget.json");
  const budgets = JSON.parse(await readFile(budgetPath, "utf8"));
  budgets.entries = replaceEntries(budgets.entries, providers, ({ definition }) => ({
    baselineGzip: definition.bundle.baselineGzip,
  }));
  budgets.notes = [
    ...budgets.notes.filter((note) => !note.startsWith("./providers/")),
    ...providers.flatMap(({ definition }) => (definition.bundle.note === undefined ? [] : [definition.bundle.note])),
  ];
  outputs.set(budgetPath, json(budgets));
  const readmePath = join(root, "README.md");
  outputs.set(readmePath, readmeList(await readFile(readmePath, "utf8"), providers));
  if (documentation)
    outputs.set(join(root, "documentation", "providers.md"), await providerInventory(documentation, providers));
  outputs.set(
    join(root, "test", "providers.generated.ts"),
    generated +
      'import type { Connector } from "../src/types.js";\n' +
      providers
        .map(
          ({ name }, index) =>
            `import { fixture as fixture${index}${`, createAuthored as authored${index}`} } from "../src/providers/${name}/fixtures.js";\n`,
        )
        .join("") +
      `\nexport const providerFixtures = [${providers.map((_, index) => `fixture${index}`).join(", ")}];\n` +
      `\nexport const providerKinds: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(providers.map(({ name, definition }) => [name, definition.kind])), null, 2)};\n` +
      `\nexport const authoredFixtures: Readonly<Record<string, (() => Pick<Connector, "listTools">) | undefined>> = {\n${providers.map(({ name }, index) => `  ${JSON.stringify(name)}: authored${index},`).join("\n")}\n};\n`,
  );
  outputs.set(join(root, "scripts", "provider-smoke.generated.mjs"), await smokeFixtures(root, providers));
  // Fixture roots without an eval harness generate no eval registrations.
  if (existsSync(join(root, "eval")))
    for (const [path, source] of await evalRegistrations(root, providers)) outputs.set(path, source);
  const stale = [];
  for (const [path, source] of outputs) {
    let previous;
    try {
      previous = await readFile(path, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (previous === source) continue;
    stale.push(path.slice(root.length + 1));
    if (!check) await writeFile(path, source);
  }
  // Operation indexes need the network to regenerate (providers:spec), so this
  // offline pass only proves each one still matches its pinned source record.
  const openapi = await checkOpenApiOutputs(root, providers);
  return { providers, outputs, stale, openapi };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  const rootIndex = args.indexOf("--root");
  const root = rootIndex === -1 ? repositoryRoot : args[rootIndex + 1];
  if (
    !root ||
    args.some((arg, index) => arg !== "--check" && arg !== "--root" && (rootIndex === -1 || index !== rootIndex + 1))
  ) {
    throw new Error("Usage: tsx scripts/generate-providers.mjs [--check] [--root directory]");
  }
  const check = args.includes("--check");
  const { providers, stale, openapi } = await generateProviders({ root, check });
  if (openapi.length) {
    console.error(`Operation indexes differ from their OpenAPI pins (run providers:spec):\n${openapi.join("\n")}`);
    process.exitCode = 1;
  }
  if (check && stale.length) {
    console.error(`Stale provider outputs (run providers:generate):\n${stale.join("\n")}`);
    process.exitCode = 1;
  } else if (!openapi.length) {
    console.log(`${providers.length} providers: generated outputs ${check ? "are current" : "updated"}`);
  }
}
