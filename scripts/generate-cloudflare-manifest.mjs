const ZERO_TRUST_PREFIXES = [
  "zeroTrust.access.applications.",
  "zeroTrust.access.policies.",
  "zeroTrust.access.serviceTokens.",
  "zeroTrust.networks.",
  "zeroTrust.tunnels.",
];

function decodeHtml(value) {
  return value
    .replaceAll("&quot;", '"')
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&amp;", "&")
    .replace(/<[^>]+>/g, "");
}

function parseOperation(line) {
  const match = line.match(
    /<code title="([a-z]+) ([^"]+)">client\.([^<]+?)\.<a href="([^"]+)">([^<]+)<\/a>(.*?) (?:-&gt;|->) (.*?)<\/code>/,
  );
  if (!match) return null;
  const [
    ,
    method,
    endpoint,
    resourcePath,
    source,
    operation,
    callTail,
    result,
  ] = match;
  const name = `${resourcePath}.${operation}`;
  if (
    resourcePath.startsWith("zeroTrust.") &&
    !ZERO_TRUST_PREFIXES.some((prefix) => name.startsWith(prefix))
  ) {
    return null;
  }
  return {
    name,
    path: [...resourcePath.split("."), operation],
    method: method.toUpperCase(),
    endpoint,
    source: source.replace(/^\.\//, ""),
    signature: decodeHtml(
      `client.${resourcePath}.${operation}${callTail} -> ${result}`,
    ),
  };
}

async function fetchResource(slug) {
  const url =
    `https://raw.githubusercontent.com/cloudflare/cloudflare-typescript/` +
    `${CLOUDFLARE_SDK_COMMIT}/src/resources/${slug}/api.md`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${response.status} fetching ${url}`);
  }
  return (await response.text())
    .split("\n")
    .map(parseOperation)
    .filter(Boolean);
}

const groups = await Promise.all(RESOURCE_SLUGS.map(fetchResource));
const operations = groups
  .flat()
  .sort((a, b) => a.name.localeCompare(b.name));

const duplicates = operations.filter(
  (operation, index) =>
    index > 0 && operation.name === operations[index - 1].name,
);
if (duplicates.length) {
  throw new Error(
    `Duplicate Cloudflare operation names: ${duplicates
      .map((operation) => operation.name)
      .join(", ")}`,
  );
}

const topLevelKeys = new Set(
  operations.map((operation) => operation.path[0]),
);
const resourceClasses = Object.entries(CloudflareResources)
  .filter(
    ([name, value]) =>
      !name.startsWith("Base") &&
      typeof value === "function" &&
      Array.isArray(value._key) &&
      value._key.length === 1 &&
      topLevelKeys.has(value._key[0]),
  )
  .map(([, value]) => value);
const client = createClient({
  apiEmail: "manifest@example.com",
  apiKey: "manifest-validation-only",
  resources: resourceClasses,
});
for (const operation of operations) {
  let owner = client;
  for (const segment of operation.path.slice(0, -1)) {
    owner = owner?.[segment];
  }
  if (typeof owner?.[operation.path.at(-1)] !== "function") {
    throw new Error(
      `Cloudflare SDK method is missing for ${operation.name}`,
    );
  }
}

const output = `// Generated by scripts/generate-cloudflare-manifest.mjs from
// cloudflare-typescript ${CLOUDFLARE_SDK_COMMIT}. Do not edit by hand.

export interface CloudflareOperation {
  name: string;
  path: readonly string[];
  method: string;
  endpoint: string;
  source: string;
  signature: string;
}

export const CLOUDFLARE_SDK_COMMIT =
  "${CLOUDFLARE_SDK_COMMIT}";

export const CLOUDFLARE_OPERATIONS: readonly CloudflareOperation[] = ${JSON.stringify(operations, null, 2)};
`;

const destination = fileURLToPath(
  new URL("../src/connectors/cloudflare-manifest.ts", import.meta.url),
);
await writeFile(destination, output);
console.log(`Generated ${operations.length} Cloudflare operations.`);
